    public static test_category_log get_log_by_name(String log_name)
    {
        test_category_log result = new test_category_log(log.get_log_by_name(log_name));
        if(!result.is_valid())
        {
            return result;
        }
        //check categories
        if (result.get_categories_count() != test_category_log.categories_count)
        {
            return new test_category_log();
        }
        for (long i = 0; i < result.get_categories_count(); ++i)
        {
            if (!test_category_log.category_names[(int)i].equals(result.get_categories_name_array().get((int)i)))
            {
                return new test_category_log();
            }
        }
        return result;
    }
    

