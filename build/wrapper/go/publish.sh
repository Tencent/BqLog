# Called only by release.yml, after the generated module has passed validation.
# Usage: publish.sh CHECKOUT GENERATED_MODULE VERSION SOURCE_COMMIT
set -euo pipefail

if [[ "${GITHUB_ACTIONS:-}" != true || "${GITHUB_WORKFLOW:-}" != "Build And Release" || "${GITHUB_EVENT_NAME:-}" != workflow_dispatch ]]; then
    echo "Go publishing is restricted to the Build And Release workflow." >&2
    exit 1
fi
if [[ $# -ne 4 ]]; then
    echo "Usage: publish.sh CHECKOUT GENERATED_MODULE VERSION SOURCE_COMMIT" >&2
    exit 1
fi
checkout="$(cd "$1" && pwd)"
module_dir="$(cd "$2" && pwd)"
version="$3"
source_commit="$4"
if [[ ! "$version" =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$ || ! "$source_commit" =~ ^[0-9a-f]{40}$ ]]; then
    echo "Invalid version or source commit." >&2
    exit 1
fi
major="${version%%.*}"
module_path="github.com/Tencent/BqLog/go"
if ((major >= 2)); then module_path="$module_path/v$major"; fi
grep -Fx "module $module_path" "$module_dir/go.mod" >/dev/null
grep -F "\"version\": \"$version\"" "$module_dir/SOURCE.json" >/dev/null
grep -F "\"source_commit\": \"$source_commit\"" "$module_dir/SOURCE.json" >/dev/null

branch=go_dist
tag="go/v$version"
branch_ref="refs/heads/$branch"
tag_ref="refs/tags/$tag"
git -C "$checkout" fetch --no-tags origin
existing_branch="$(git -C "$checkout" ls-remote --heads origin "$branch_ref" | cut -f1)"
existing_tag="$(git -C "$checkout" ls-remote --tags origin "$tag_ref" | cut -f1)"

# Use a private index/tree, never switch or delete the development checkout.
temp_dir="$(mktemp -d)"
trap 'rm -rf -- "$temp_dir"' EXIT
mkdir -p "$temp_dir/tree/go"
cp -R "$module_dir/." "$temp_dir/tree/go/"
printf '# BqLog Go source distribution\n\nGenerated by release.yml from %s. Do not edit this branch.\n' "$source_commit" > "$temp_dir/tree/README.md"
git_dir="$(git -C "$checkout" rev-parse --absolute-git-dir)"
export GIT_DIR="$git_dir"
export GIT_WORK_TREE="$temp_dir/tree"
export GIT_INDEX_FILE="$temp_dir/index"
cd "$GIT_WORK_TREE"
git read-tree --empty
git add --all
tree="$(git write-tree)"

if [[ -n "$existing_tag" ]]; then
    git fetch --no-tags origin "$tag_ref"
    tag_tree="$(git rev-parse 'FETCH_HEAD^{tree}')"
    if [[ "$tree" != "$tag_tree" ]]; then
        echo "Refusing to overwrite published $tag with different source." >&2
        exit 1
    fi
    echo "$tag already publishes this exact module; nothing to do."
    exit 0
fi

parent=()
if [[ -n "$existing_branch" ]]; then
    git fetch --no-tags origin "$branch_ref"
    # Do not rewind the generated branch when rerunning an older release.
    previous="$(git show FETCH_HEAD:go/SOURCE.json | sed -n 's/.*"version": "\([^"]*\)".*/\1/p')"
    # A stable release follows every prerelease of the same numeric version.
    ordered_previous="$previous"
    ordered_version="$version"
    if [[ "$previous" != *-* ]]; then ordered_previous="$previous-z"; fi
    if [[ "$version" != *-* ]]; then ordered_version="$version-z"; fi
    highest="$(printf '%s\n%s\n' "$ordered_previous" "$ordered_version" | sort -V | tail -n1)"
    if [[ "$highest" != "$ordered_version" ]]; then
        echo "Refusing to publish $version over newer go_dist $previous." >&2
        exit 1
    fi
    parent=(-p "$existing_branch")
fi
export GIT_AUTHOR_NAME='github-actions[bot]'
export GIT_AUTHOR_EMAIL='41898282+github-actions[bot]@users.noreply.github.com'
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME"
export GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"
commit="$(printf 'Publish BqLog Go %s\n\nSource-Commit: %s\n' "$version" "$source_commit" | git commit-tree "$tree" "${parent[@]}")"
# Both refs are created together. No force push or mutable version tags.
git push --atomic origin "$commit:$branch_ref" "$commit:$tag_ref"
echo "Published $module_path@v$version from $source_commit"
