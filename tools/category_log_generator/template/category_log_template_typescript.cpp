    const static char* TAB = "    ";
    bq::string category_log_template_typescript_base::format(const bq::string& template_string, const category_node& root_node) const
    {
        bq::string generated_code = template_string;
        generated_code = replace_with_tab_format(generated_code, "${CLASS_NAME}", class_name_);
        generated_code = replace_with_tab_format(generated_code, "${CATEGORY_NAMES}", get_category_names_code(root_node));
        generated_code = replace_with_tab_format(generated_code, "${CATEGORY_ROOT_CLASS}", get_category_class_root_define_code(root_node));

        return generated_code;
    }

    bq::string category_log_template_typescript_base::get_category_names_code_recursive(const category_node& node) const
    {
        bq::string tab = "    ";
        bq::string code = tab;
        if (node.parent()) // empty means it is root node, first value
        {
            code += ", ";
        }
        code += "\"" + node.full_name() + "\"\n";
        for (const auto& child : node.get_all_children()) {
            code += get_category_names_code_recursive(*child);
        }
        return code;
    }
    bq::string category_log_template_typescript_base::get_category_class_code_recursive(const category_node& node, const bq::string& tab, uint64_t& index) const
    {
        bq::string node_class_name = class_name_ + "_" + node.name();
        bq::string code = tab + "/** The " + node.full_name() + " category. */\n";
        code += tab + "public readonly " + node.name() + " = new (class " + node_class_name + " extends " + class_name_ + "_category_base {\n";
        code += tab + TAB + "constructor() {\n";
        code += tab + TAB + TAB + "super(" + uint64_to_string(++index) + ");\n";
        code += tab + TAB + "}\n";
        for (const auto& child : node.get_all_children()) {
            code += get_category_class_code_recursive(*child, tab + TAB, index);
        }
        code += tab + "})();\n";
        return code;
    }

    bq::string category_log_template_typescript_base::get_category_names_code(const category_node& root_node) const
    {
        bq::string code = "[\n";
        code += get_category_names_code_recursive(root_node);
        code += "]";
        return code;
    }

    bq::string category_log_template_typescript_base::get_category_class_root_define_code(const category_node& root_node) const
    {
        bq::string code = "/** The categories declared by the category configuration. */\n";
        code += "class " + class_name_ + "_category_root\n";
        code += "{\n";
        uint64_t index = 0;
        for (const auto& child : root_node.get_all_children()) {
            code += get_category_class_code_recursive(*child, "    ", index);
        }
        code += "}\n";
        return code;
    }

